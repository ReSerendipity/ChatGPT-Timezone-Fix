    root = os.path.join(here, "..", "_locales")
    os.makedirs(root, exist_ok=True)
    for code in LOCALES:
        trans = T.get(code, {})
        messages = {}
        for key, en_msg in EN.items():
            msg = trans.get(key, en_msg)
            entry = {"message": msg}
            if key in DESC:
                entry["description"] = DESC[key]
            messages[key] = entry
        dest = os.path.join(root, code, "messages.json")
        os.makedirs(os.path.dirname(dest), exist_ok=True)
        with open(dest, "w", encoding="utf-8") as f:
            json.dump(messages, f, ensure_ascii=False, indent=2)
            f.write("\n")
        missing = [k for k in EN if k not in trans]
        print("wrote %s (%d keys%s)" % (dest, len(EN), ", translated" if not missing else ", MISSING: %s" % missing))
    print("done: %d locales" % len(LOCALES))


